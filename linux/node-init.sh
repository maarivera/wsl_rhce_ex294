#!/usr/bin/env bash
# node-init.sh - personalize a clone of the golden image as one lab node.
#
# Usage (as root, from the repository root):
#   bash linux/node-init.sh --role managed --name managed-node1 --ip 10.10.10.11 \
#        --disks "disk1:1024" --seed-vg research:disk1
#   bash linux/node-init.sh --role control --name control-node --ip 10.10.10.10
#
# Restart the distribution afterwards (wsl --terminate NAME) so the hostname and
# the network namespace take effect.
set -euo pipefail

ROLE="" NAME="" IP="" DISKS="" SEED_VG=""
DOMAIN=lab.example.com
while [[ $# -gt 0 ]]; do
    case $1 in
        --role) ROLE=$2; shift 2 ;;
        --name) NAME=$2; shift 2 ;;
        --ip) IP=$2; shift 2 ;;
        --disks) DISKS=$2; shift 2 ;;
        --seed-vg) SEED_VG=$2; shift 2 ;;
        *) echo "unknown option $1" >&2; exit 2 ;;
    esac
done
[[ $ROLE == control || $ROLE == managed ]] || { echo "--role control|managed required" >&2; exit 2; }
[[ -n $NAME && -n $IP ]] || { echo "--name and --ip required" >&2; exit 2; }
[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

# Services that must listen on the node's own address. On managed nodes they are
# started inside the node's network namespace. Add more here if an exercise needs it.
NETNS_SERVICES=(sshd firewalld httpd nginx php-fpm mariadb mysqld postgresql vsftpd
    postfix crond atd chronyd named smb nmb nfs-server rsyslog)

log() { printf '==> [%s] %s\n' "$NAME" "$*"; }

log "Writing /etc/rhcelab/lab.conf"
mkdir -p /etc/rhcelab
cat >/etc/rhcelab/lab.conf <<EOF
# Generated by node-init.sh
LAB_ROLE=$ROLE
LAB_NODE=$NAME
LAB_DOMAIN=$DOMAIN
LAB_IP=$IP
LAB_PREFIX=24
LAB_SUBNET=10.10.10.0/24
LAB_GW=10.10.10.1
LAB_BRIDGE=rhcebr0
LAB_NETNS=rhcelab
LAB_VETH=rlv${IP##*.}
LAB_DISKS="$DISKS"
LAB_SEED_VG="$SEED_VG"
EOF

log "Hostname and name resolution (no external DNS needed for lab names)"
sed -i '/^hostname *=/d' /etc/wsl.conf
sed -i "/^\[network\]/a hostname = $NAME" /etc/wsl.conf
cat >/etc/hosts <<EOF
127.0.0.1   localhost localhost.localdomain localhost4 localhost4.localdomain4
::1         localhost localhost.localdomain localhost6 localhost6.localdomain6

# RHCE lab (10.10.10.0/24 on bridge rhcebr0)
10.10.10.1  lab-gateway.$DOMAIN lab-gateway
10.10.10.10 control-node.$DOMAIN control-node materials.$DOMAIN
10.10.10.11 managed-node1.$DOMAIN managed-node1
10.10.10.12 managed-node2.$DOMAIN managed-node2
EOF

log "Unique identity: machine-id and SSH host keys"
rm -f /etc/machine-id && systemd-machine-id-setup >/dev/null
rm -f /etc/ssh/ssh_host_*
ssh-keygen -A >/dev/null

if [[ $ROLE == managed ]]; then
    log "Placing network services in the node's network namespace"
    for svc in "${NETNS_SERVICES[@]}"; do
        mkdir -p "/etc/systemd/system/$svc.service.d"
        cat >"/etc/systemd/system/$svc.service.d/10-rhcelab-netns.conf" <<'EOF'
# rhcelab: run this service in the managed node's own network namespace.
[Unit]
Requires=rhcelab-net.service
After=rhcelab-net.service

[Service]
NetworkNamespacePath=/run/netns/rhcelab
EOF
    done
    systemctl enable sshd firewalld rhcelab-net.service rhcelab-storage.service
else
    log "Control node: it lives in the shared WSL namespace, so no sshd and no firewalld"
    # Both would bind/filter the namespace that every other WSL distro also uses.
    systemctl disable sshd firewalld rhcelab-storage.service 2>/dev/null || true
    systemctl mask firewalld
    systemctl enable rhcelab-net.service
fi
log "Done - restart the distribution: wsl --terminate $NAME"
